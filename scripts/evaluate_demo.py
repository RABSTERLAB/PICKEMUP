"""Evaluate engines on the synthetic corpus with ground truth. Writes docs/evaluation/DEMO_EVAL.md."""
import sys, io, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / "packages" / "analysis-core"), str(ROOT / "packages" / "connectors")]
from collections import defaultdict
from pickemup_connectors.synthetic import SyntheticCampaignConnector
from pickemup_analysis.automation import score_account
from pickemup_analysis.coordination import detect_coordination
from pickemup_analysis.evaluate import binary_eval

batch = SyntheticCampaignConnector().run({"seed": 1337})
gt = batch.provenance["account_ground_truth"]
by_acct = defaultdict(list)
for p in batch.posts:
    by_acct[p.author_id].append(p)

# --- automation: truth = ANY automated label (coordinated swarm + benign feeds) ---
truth = {a for a, l in gt.items() if l in ("automated_coordinated", "benign_automated")}
pred = set()
for a in batch.accounts:
    r = score_account(a.account_id, by_acct.get(a.account_id, []), {"default_profile": a.default_profile})
    if r.verdict == "likely_automated":
        pred.add(a.account_id)
auto = binary_eval("automation (any automated)", truth, pred, set(gt))

# --- coordination: pair-level (standard in coordination-detection research) ---
reports, edges, _ = detect_coordination(batch.accounts, batch.posts)
strong = [r for r in reports if r.verdict == "human_coordinated_possible"]
covered = set()
for r in strong:
    covered |= set(r.members)
coord_groups = {"automated_coordinated", "human_coordinated"}
truth_pairs, pred_pairs = set(), set()
group_of = {a: l for a, l in gt.items()}
members = [a.account_id for a in batch.accounts if a.ground_truth_label in coord_groups]
import itertools
truth_pairs = {frozenset(p) for p in itertools.combinations(members, 2)
               if group_of[p[0]] == group_of[p[1]]}
for r in strong:
    mm = [m for m in r.members]
    pred_pairs |= {frozenset(p) for p in itertools.combinations(mm, 2)}
all_accounts = set(gt)
coord = binary_eval("coordination pairs (same-group)", truth_pairs, pred_pairs, all_accounts)
fp_bad_pairs = pred_pairs - truth_pairs
fp_bad_accts = {a for p in fp_bad_pairs for a in p} & {
    a for a, l in gt.items() if l in ("organic", "benign_human_active", "benign_human")}

lines = [
    "# Demo evaluation (measured, reproducible)",
    "",
    f"Generated by `scripts/evaluate_demo.py` on synthetic corpus seed 1337 "
    f"({len(batch.accounts)} accounts, {len(batch.posts)} posts), algo 2026.10-mvp1.",
    "",
    "| metric | TP | FP | FN | TN | precision | recall | F1 |",
    "|---|---|---|---|---|---|---|---|",
]
for ev in (auto, coord):
    lines.append(f"| {ev.label} | {ev.tp} | {ev.fp} | {ev.fn} | {len(list())} | "
                 f"{ev.precision:.3f} | {ev.recall:.3f} | {ev.f1:.3f} |")
lines += [
    "",
    f"- Benign-high-activity / organic accounts appearing in a *strong* cluster via a false pair: "
    f"**{len(fp_bad_accts)}** (negative-test requirement).",
    f"- Strong clusters: {[(r.cluster_id, r.accounts, r.confidence) for r in strong]}",
    f"- All other clusters verdicted `indeterminate` with organic explanations: "
    f"{[(r.cluster_id, r.accounts) for r in reports if r not in strong]}",
    "",
    "Known gaps: 1 swarm account below the 2-family gate at low post counts; astroturf recall limited by",
    "probabilistic repost membership (seed 1337). These are engine limitations, not metric rounding.",
    "Scores measured on synthetic textbook patterns ONLY — not evidence of live-network accuracy.",
    "",
]
out = ROOT / "docs" / "evaluation" / "DEMO_EVAL.md"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(lines), encoding="utf-8")
print("\n".join(lines))
